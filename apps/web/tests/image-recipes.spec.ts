import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {selectEditorTool} from './editor-helpers';

test('before/after recipe uses editable uploaded slots, previews actual pixels and exports the same comparison with undo',async({page})=>{
 const posts:string[]=[];page.on('request',request=>{if(request.method()==='POST')posts.push(request.url());});
 await page.goto('/preview/editor/image');
 await selectEditorTool(page,'Image','Templates');
 const apply=page.getByRole('button',{name:'Apply before / after recipe',exact:true});
 await expect(apply).toBeDisabled();
 const asset=async(color:string)=>Buffer.from(await page.evaluate(color=>{const canvas=document.createElement('canvas');canvas.width=200;canvas.height=200;const ctx=canvas.getContext('2d')!;ctx.fillStyle=color;ctx.fillRect(0,0,200,200);return canvas.toDataURL().split(',')[1];},color),'base64');
 await selectEditorTool(page,'Image','Media');
 await page.getByLabel('Choose image',{exact:true}).setInputFiles({name:'before.png',mimeType:'image/png',buffer:await asset('#ff0000')});
 await selectEditorTool(page,'Image','Layers');
 await page.getByLabel('Add image overlay',{exact:true}).setInputFiles({name:'after.png',mimeType:'image/png',buffer:await asset('#0000ff')});
 const original=await page.getByLabel('Edited image preview',{exact:true}).evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL());
 await selectEditorTool(page,'Image','Templates');
 await expect(apply).toBeDisabled();
 await page.getByLabel('Comparison after photo',{exact:true}).selectOption({label:'after.png'});
 await page.getByLabel('Comparison before label',{exact:true}).fill('Sebelum');
 await page.getByLabel('Comparison after label',{exact:true}).fill('Selepas');
 const draft=page.getByLabel('Before and after recipe preview',{exact:true});
 const pixels=(label:string)=>page.getByLabel(label,{exact:true}).evaluate(canvas=>{const ctx=(canvas as HTMLCanvasElement).getContext('2d')!;return [50,150].map(x=>Array.from(ctx.getImageData(x,92,1,1).data));});
 await expect.poll(()=>pixels('Before and after recipe preview')).toEqual([[255,0,0,255],[0,0,255,255]]);
 const proposed=await draft.evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL());
 await apply.click();
 await expect.poll(()=>page.getByLabel('Edited image preview',{exact:true}).evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL())).toBe(proposed);
 await selectEditorTool(page,'Image','Adjust & text');
 await expect(page.getByLabel('Image caption',{exact:true})).toHaveValue('Sebelum → Selepas');
 await selectEditorTool(page,'Image','Export');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export image',exact:true}).click();
 const file=await download,encoded=(await readFile((await file.path())!)).toString('base64');
 expect(file.suggestedFilename()).toBe('orbit-slide-01.png');
 const decoded=await page.evaluate(async encoded=>{const image=new Image();image.src='data:image/png;base64,'+encoded;await image.decode();const canvas=document.createElement('canvas');canvas.width=image.naturalWidth;canvas.height=image.naturalHeight;const ctx=canvas.getContext('2d')!;ctx.drawImage(image,0,0);return {width:canvas.width,height:canvas.height,pixels:[50,150].map(x=>Array.from(ctx.getImageData(x,92,1,1).data))};},encoded);
 expect(decoded).toEqual({width:200,height:200,pixels:[[255,0,0,255],[0,0,255,255]]});
 await page.getByRole('button',{name:'Undo last composition',exact:true}).click();
 await expect.poll(()=>page.getByLabel('Edited image preview',{exact:true}).evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL())).toBe(original);
 expect(posts).toEqual([]);
});
